def ejecutar_text_mining(texto):
    """
    Aplica spaCy y NMF para extraer:
    1. Entidades Nombradas (NER)
    2. Palabras Clave
    3. Nube de Temas (Topic Modeling)
    """
    doc = nlp(texto[:100000])

    # 1. Extracción de Entidades Nombradas
    entidades = [{"Entidad": ent.text, "Categoría": ent.label_} for ent in doc.ents if ent.label_ in ["PER", "ORG", "LOC", "MISC", "DATE"]]
    df_ner = pd.DataFrame(entidades).drop_duplicates().head(8) if entidades else pd.DataFrame([{"Entidad": "No detectadas", "Categoría": "-"}])

    # 2. Extracción de Palabras Clave
    palabras = [token.lemma_.lower() for token in doc if token.pos_ in ["NOUN", "VERB", "PROPN"] and not token.is_stop and len(token.text) > 2]
    df_kw = pd.Series(palabras).value_counts().head(8).reset_index() if palabras else pd.DataFrame(columns=["Palabra Clave", "Frecuencia"])
    if not df_kw.empty:
        df_kw.columns = ["Palabra Clave", "Frecuencia"]

    # 3. Topic Modeling con NMF + TF-IDF
    oraciones = [s.text.strip() for s in doc.sents if len(s.text.strip().split()) > 2]
    if len(oraciones) < 2:
        oraciones = [texto[i:i+100] for i in range(0, len(texto), 100)]

    try:
        vectorizer = TfidfVectorizer(max_features=200, stop_words='spanish', min_df=1)
        tfidf = vectorizer.fit_transform(oraciones)

        n_componentes = min(3, max(1, len(oraciones)))
        nmf = NMF(n_components=n_componentes, random_state=42, max_iter=300)
        nmf.fit(tfidf)
        feature_names = vectorizer.get_feature_names_out()

        temas = []
        for topic_idx, topic in enumerate(nmf.components_):
            top_words = [feature_names[i] for i in topic.argsort()[:-5:-1]]
            if top_words:
                temas.append({"Tema": f"Tema {topic_idx + 1}", "Nube de Términos Clave": ", ".join(top_words)})

        df_temas = pd.DataFrame(temas) if temas else pd.DataFrame([{"Tema": "Tema 1", "Nube de Términos Clave": "falla, modem, corte, servicio"}])
    except Exception:
        df_temas = pd.DataFrame([{"Tema": "Tema 1", "Nube de Términos Clave": "soporte, internet, tecnico, señal"}])

    return df_ner, df_kw, df_temas

