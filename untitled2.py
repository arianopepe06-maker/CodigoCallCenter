def analizar_sentimiento_beto(texto):
    """
    Clasifica el sentimiento de un texto usando el modelo BETO.
    Devuelve un puntaje numérico (-1.0 a +1.0) y la etiqueta (Positivo, Neutro, Negativo).
    """
    if not texto.strip():
        return 0.0, "Neutro"

    # Predecir con BETO (limite de 512 tokens)
    resultado = analizador_beto.predict(texto[:512])
    label = resultado.output
    probas = resultado.probas

    # Transformación a una escala lineal de polaridad
    if label == "POS":
        score = round(probas["POS"], 2)
        etiqueta = "Positivo"
    elif label == "NEG":
        score = round(-probas["NEG"], 2)
        etiqueta = "Negativo"
    else:
        score = 0.0
        etiqueta = "Neutro"

    return score, etiqueta

def procesar_bloques_temporales(texto, duracion_minutos=45):
    """
    Divide el texto de manera proporcional respetando la DURACIÓN REAL de la llamada
    en intervalos fijados de 3 minutos cada uno.
    """
    lineas = [l.strip() for l in texto.strip().split('\n') if l.strip()]
    if not lineas:
        lineas = [texto]

    intervalo = 3  # Tamaño de bloque en minutos
    total_bloques = max(1, int(np.ceil(duracion_minutos / intervalo)))

    # Calcular cuántas líneas corresponden a cada bloque de tiempo
    lineas_por_bloque = max(1, int(np.ceil(len(lineas) / total_bloques)))

    bloques = []
    for i in range(total_bloques):
        min_inicio = i * intervalo
        min_fin = min((i + 1) * intervalo, duracion_minutos)

        inicio_idx = i * lineas_por_bloque
        fin_idx = min((i + 1) * lineas_por_bloque, len(lineas))

        # Extraer fragmento correspondiente a este tramo de tiempo
        sub_texto = " ".join(lineas[inicio_idx:fin_idx])

        if sub_texto.strip():
            score, etiqueta = analizar_sentimiento_beto(sub_texto)
        else:
            score, etiqueta = 0.0, "Neutro"
            sub_texto = "[Sin registro de diálogo]"

        bloques.append({
            "Bloque": f"Min {min_inicio:02d} - {min_fin:02d}",
            "Texto": sub_texto,
            "Polaridad (BETO)": score,
            "Etiqueta Sentimiento": etiqueta
        })

    return pd.DataFrame(bloques)

