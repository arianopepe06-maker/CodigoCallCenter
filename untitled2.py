def procesar_archivo(archivo):
    if archivo is None:
        return [None] * 13

    # Lectura del archivo de entrada
    if archivo.name.endswith('.csv'):
        df = pd.read_csv(archivo.name)
        datos = df.iloc[0].to_dict()
    elif archivo.name.endswith('.json'):
        with open(archivo.name, 'r', encoding='utf-8') as f:
            datos = json.load(f)
    else:
        return [None] * 13

    texto = datos.get("texto", "")

    # Obtener duración real en minutos (Extrae números de textos como "45 min")
    duracion_str = str(datos.get('duracion', '45')).lower()
    numeros = re.findall(r'\d+', duracion_str)
    duracion_num = int(numeros[0]) if numeros else 45

    # Construcción de textos explicativos para la interfaz
    info_general = f"""
    <div><b>ID Llamada:</b> {datos.get('id_llamada', 'N/A')}</div>
    <div><b>Cliente:</b> {datos.get('nombre', 'N/A')} (DNI: {datos.get('dni', 'N/A')})</div>
    <div><b>Teléfono:</b> {datos.get('telefono', 'N/A')}</div>
    <div><b>Servicio:</b> {datos.get('servicio', 'N/A')}</div>
    <div><b>Agente:</b> {datos.get('agente', 'N/A')}</div>
    <div><b>Duración Real:</b> {duracion_num} min</div>
    """

    alertas = f"⚠️ <b>Alerta Técnica:</b> Interrupción de enlace por falla física en ONT. Orden de visita generada."
    resumen_ejecutivo = f"El cliente {datos.get('nombre', 'registrado')} reporta caída total del servicio de internet. El agente ejecuta pruebas de nivel 1 y programa la asistencia técnica presencial."
    detalle_problema = datos.get('motivo', 'Falla técnica de conectividad.')

    # Procesar bloques de tiempo considerando la duración real completa
    df_bloques = procesar_bloques_temporales(texto, duracion_minutos=duracion_num)

    # Generar y guardar el gráfico temporal
    temp_img_path = os.path.join(tempfile.gettempdir(), "grafico_sentimiento.png")
    generar_grafico_sentimiento(df_bloques, temp_img_path)

    comportamiento_txt = "<b>Análisis BETO:</b> Transición de nivel de insatisfacción inicial hacia estabilidad tras la asignación de una solución técnica."

    # Ejecutar Text Mining
    df_ner, df_kw, df_temas = ejecutar_text_mining(texto)

    evaluacion_txt = """
    <div><b>Calificación Agente:</b> ⭐ 4.8 / 5.0</div>
    <div><b>Empatía:</b> Excelente comunicación y contención al cliente.</div>
    <div><b>Protocolo:</b> Validación completa de identidad y procesos técnicos.</div>
    """
    oportunidades_txt = "Optimizar tiempos de derivación cuando el módem reporte pérdida de enlace óptico."

    # Exportar el reporte en PDF
    pdf_path = generar_pdf_reporte(datos, df_bloques, temp_img_path, df_temas)

    return (
        df_bloques,
        info_general,
        comportamiento_txt,
        evaluacion_txt,
        resumen_ejecutivo,
        detalle_problema,
        oportunidades_txt,
        alertas,
        temp_img_path,
        df_ner,
        df_kw,
        df_temas,
        pdf_path
    )

